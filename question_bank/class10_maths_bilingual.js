const dedupeOptions = (options, correctAnswer, fallbacks) => {
  const result = [...options];
  const normalize = (value) => String(value).trim().toLowerCase();
  const useFallback = (index) => {
    for (const fallback of fallbacks) {
      if (!result.some((value, valueIndex) => valueIndex !== index && normalize(value) === normalize(fallback))) {
        result[index] = fallback;
        return;
      }
    }
    result[index] = `Alternative ${index + 1}`;
  };

  for (let index = 0; index < result.length; index += 1) {
    if (index !== correctAnswer && normalize(result[index]) === normalize(result[correctAnswer])) {
      useFallback(index);
    }
  }

  const seen = new Set();
  for (let index = 0; index < result.length; index += 1) {
    const key = normalize(result[index]);
    if (seen.has(key)) useFallback(index);
    seen.add(normalize(result[index]));
  }

  return result;
};

const makeQuestionSet = (topicId, prefix, specs) =>
  specs.map((spec, index) => {
    const correctAnswer = index % 4;
    const options = [...spec.distractors];
    const optionsHindi = [...spec.distractorsHindi];
    options.splice(correctAnswer, 0, spec.answer);
    optionsHindi.splice(correctAnswer, 0, spec.answerHindi);
    const uniqueOptions = dedupeOptions(options.slice(0, 4), correctAnswer, [
      "None of these",
      "Cannot be determined",
      "All of these",
      "Not enough information",
    ]);
    const uniqueOptionsHindi = dedupeOptions(optionsHindi.slice(0, 4), correctAnswer, [
      "इनमें से कोई नहीं",
      "निर्धारित नहीं किया जा सकता",
      "ये सभी",
      "पर्याप्त जानकारी नहीं",
    ]);
    return makeQuestion({
      id: `${prefix}-${String(index + 1).padStart(2, "0")}`,
      topicId,
      tags: spec.tags,
      question: spec.question,
      questionHindi: spec.questionHindi,
      options: uniqueOptions,
      optionsHindi: uniqueOptionsHindi,
      correctAnswer,
      hints: [spec.hint],
      hintsHindi: [spec.hintHindi],
      explanation: spec.explanation,
      explanationHindi: spec.explanationHindi,
      difficulty: spec.difficulty,
      eloRating: spec.eloRating,
      questionImage: spec.questionImage,
    });
  });

